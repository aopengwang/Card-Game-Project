const SERVER_ERRORS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^the room is full$/, () => t("err.roomFull")],
  [/^the game has already started$|^the game is already running$/, () => t("err.started")],
  [/^no such room$/, () => t("err.noRoom")],
  [/^need (\d+)-(\d+) players$/, (m) => t("err.needPlayers", { min: m[1], max: m[2] })],
  [/^only the host /, () => t("err.hostOnly")],
  [/^settings can't change during a game$/, () => t("err.settingsLocked")],
  [/^this room needs a password$/, () => t("err.needPassword")],
  [/^wrong password$/, () => t("err.wrongPassword")],
  [/^too many wrong passwords/, () => t("err.tooManyPasswords")],
  [/^the password (must be text|can be at most)/, () => t("err.passwordBad")],
  [/^you're sending messages too fast$/, () => t("err.chatTooFast")],
  [/^you're sending emotes too fast$/, () => t("err.emoteTooFast")],
  [/^enable at least (\d+) heroes for \d+ players$/, (m) => t("err.enableHeroes", { n: m[1] })],
  [/^that request is no longer active$/, () => t("err.stale")],
  [/^this isn't a test room$/, () => t("err.notTestRoom")],
  [/^no such card left in the draw or discard pile$/, () => t("err.testCard")],
  [/^that card isn't in this deck/, () => t("err.testDeck")],
  [/^HP must be between 1 and (\d+)$/, (m) => t("err.testHp", { max: m[1] })],
  [/^that player is dead$/, () => t("err.deadPlayer")],
  [/^unknown room or token$/, () => t("err.badToken")],
];

/** Server messages are English; show a translation when we know the message. */
export function serverText(msg: string): string {
  for (const [re, fn] of SERVER_ERRORS) {
    const m = msg.match(re);
    if (m) return fn(m);
  }
  return lang === "en" ? msg : t("err.invalid", { detail: msg });
}

